import { countBySeverity, SEVERITIES, sortFindings, type EvidenceSpan, type Finding, type FindingLink, type Report } from './model.ts';

/** Options for {@link renderMarkdown}. */
export interface MarkdownOptions {
  /** Most findings shown in the table and details; the rest are counted. Defaults to 50. */
  readonly maxFindings?: number;
  /** Snippets longer than this many lines are cut. Defaults to 30. */
  readonly maxSnippetLines?: number;
}

const MARKER_PREFIX = '<!-- forge-core:report';

/**
 * The hidden HTML comment that starts every rendered report, for example
 * `<!-- forge-core:report tool=proof -->`. A later run looks for it to update
 * the same PR comment. Characters outside `[A-Za-z0-9._-]` in `tool` become `_`.
 */
export function reportMarker(tool: string): string {
  return `${MARKER_PREFIX} tool=${tool.replace(/[^A-Za-z0-9._-]/g, '_')} -->`;
}

/**
 * True when `body` was rendered for `tool` by {@link renderMarkdown}. Only the first
 * line counts, so a marker quoted inside a snippet or a user's text does not match.
 */
export function hasReportMarker(body: string, tool: string): boolean {
  const firstLine = body.split('\n', 1)[0] ?? '';
  return firstLine.trimEnd() === reportMarker(tool);
}

/**
 * Renders a report as Markdown for a PR comment: a hidden marker, a summary line,
 * a table sorted by severity and a collapsible section per finding.
 * All text from the report is escaped, so it cannot add HTML, links or table cells.
 */
export function renderMarkdown(report: Report, options: MarkdownOptions = {}): string {
  const maxFindings = positiveInt('maxFindings', options.maxFindings ?? 50);
  const maxSnippetLines = positiveInt('maxSnippetLines', options.maxSnippetLines ?? 30);
  const sorted = sortFindings(report.findings);
  const shown = sorted.slice(0, maxFindings);
  const hidden = sorted.length - shown.length;

  const parts: string[] = [reportMarker(report.tool), `### ${escapeText(report.tool)} report`, subjectLine(report)];
  if (report.summary.trim() !== '') parts.push(escapeBlock(report.summary));
  if (shown.length > 0) parts.push(table(shown));
  if (hidden > 0) parts.push(`_${hidden} more ${hidden === 1 ? 'finding is' : 'findings are'} not shown._`);
  for (const finding of shown) parts.push(details(finding, maxSnippetLines));
  parts.push(
    `<sub>Generated by ${escapeText(report.tool)} ${escapeText(report.version)} at ${escapeText(report.generatedAt)}</sub>`,
  );
  return `${parts.join('\n\n')}\n`;
}

function subjectLine(report: Report): string {
  const count = report.findings.length;
  const name = linkOrText(report.subject.name, report.subject.url);
  const about = `${escapeText(report.subject.kind)} ${name}`;
  if (count === 0) return `No findings for ${about}.`;
  const counts = countBySeverity(report.findings);
  const bySeverity = [...SEVERITIES]
    .reverse()
    .filter((s) => counts[s] > 0)
    .map((s) => `${counts[s]} ${s}`)
    .join(', ');
  return `**${count} ${count === 1 ? 'finding' : 'findings'}** (${bySeverity}) for ${about}.`;
}

function table(findings: readonly Finding[]): string {
  const rows = findings.map(
    (f) =>
      `| ${f.severity} | ${escapeText(f.ruleId)} | ${escapeText(f.title)} | ${location(f.evidence)} | ${percent(f.confidence)} |`,
  );
  return ['| Severity | Rule | Finding | Location | Confidence |', '| --- | --- | --- | --- | --- |', ...rows].join('\n');
}

function details(finding: Finding, maxSnippetLines: number): string {
  const lines = [
    '<details>',
    // This line is inside an HTML block, where Markdown escapes are not processed: escape as HTML.
    `<summary><strong>${finding.severity.toUpperCase()}</strong> ${escapeHtml(finding.title)} (${escapeHtml(finding.ruleId)})</summary>`,
    '',
  ];
  if (finding.message.trim() !== '') lines.push(escapeBlock(finding.message), '');
  for (const span of finding.evidence) {
    lines.push(`**${location([span])}**`, '');
    if (span.snippet !== undefined && span.snippet !== '') lines.push(codeBlock(span.snippet, maxSnippetLines), '');
  }
  if (finding.links.length > 0) {
    lines.push(finding.links.map((link) => `- ${linkFor(link)}`).join('\n'), '');
  }
  lines.push(`Confidence ${percent(finding.confidence)}. Finding id: ${escapeText(finding.id)}`, '', '</details>');
  return lines.join('\n');
}

function location(evidence: readonly EvidenceSpan[]): string {
  const first = evidence[0];
  if (first === undefined) return '-';
  const lines = first.endLine > first.startLine ? `${first.startLine}-${first.endLine}` : `${first.startLine}`;
  const more = evidence.length > 1 ? ` (+${evidence.length - 1} more)` : '';
  return `${escapeText(first.file)}:${lines}${more}`;
}

function percent(confidence: number): string {
  return `${Math.round(Math.min(1, Math.max(0, confidence)) * 100)}%`;
}

function linkFor(link: FindingLink): string {
  return linkOrText(link.label, link.url);
}

/** A Markdown link when `url` is a valid http(s) URL; otherwise just the escaped text. */
function linkOrText(text: string, url: string | undefined): string {
  const href = safeUrl(url);
  return href === undefined ? escapeText(text) : `[${escapeText(text)}](<${href}>)`;
}

function safeUrl(url: string | undefined): string | undefined {
  if (url === undefined || !URL.canParse(url)) return undefined;
  const parsed = new URL(url);
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') return undefined;
  // `href` percent-encodes spaces and `<`; encode `>` too so it cannot end the `<...>` destination.
  return parsed.href.replace(/>/g, '%3E');
}

/**
 * A fenced code block whose fence is longer than any run of backticks in `code`,
 * so the snippet cannot close it early (CommonMark fenced code rules).
 */
function codeBlock(code: string, maxLines: number): string {
  const all = code.replace(/\r\n?/g, '\n').replace(/\n+$/, '').split('\n');
  const kept = all.slice(0, maxLines);
  if (all.length > kept.length) kept.push(`... (${all.length - kept.length} more lines)`);
  const body = kept.join('\n');
  const longestRun = Math.max(0, ...(body.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(Math.max(3, longestRun + 1));
  return `${fence}\n${body}\n${fence}`;
}

/** Characters that change meaning anywhere in a line, including GFM table pipes and strikethrough. */
const INLINE_SPECIAL = /[\\`*_[\]|~]/g;

/** Starts of a line that would make a heading, list, quote or rule. */
const BLOCK_START = /^(?:([#+\-=])|(\d+)([.)]))/;

/**
 * Escapes untrusted text for inline Markdown, such as a table cell: newlines become
 * spaces, `<`, `>` and `&` become HTML entities, Markdown punctuation gets a backslash
 * and `@` gets a zero-width space so the text cannot mention (notify) users.
 * The result cannot open HTML tags, comments, links or new table cells.
 */
export function escapeText(text: string): string {
  return text
    .replace(/\r\n?|\n/g, ' ')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/@/g, '@&#8203;')
    .replace(INLINE_SPECIAL, (ch) => `\\${ch}`);
}

/** Escapes text for raw HTML content, also breaking `@` mentions. Newlines become spaces. */
function escapeHtml(text: string): string {
  return text
    .replace(/\r\n?|\n/g, ' ')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/@/g, '@&#8203;');
}

/**
 * Escapes multi-line untrusted text that starts its own lines, such as a message.
 * Line breaks are kept. Leading spaces are dropped so a line cannot become an indented
 * code block, and a leading `#`, `-`, `+`, `=` or `1.` is escaped so it cannot start
 * a heading or list.
 */
export function escapeBlock(text: string): string {
  return text
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) =>
      escapeText(line.trimStart()).replace(BLOCK_START, (_all, mark: string | undefined, digits = '', dot = '') =>
        mark !== undefined ? `\\${mark}` : `${digits}\\${dot}`,
      ),
    )
    .join('  \n');
}

function positiveInt(name: string, value: number): number {
  if (!Number.isInteger(value) || value < 1) throw new RangeError(`${name} must be a positive integer, got ${value}`);
  return value;
}
